"""Generate src/themes.py from the Ingama Textil theme CSS files (palettes) plus Sunshine's own wallpaper-derived themes."""
import re, sys, os, json
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/Projects/work-ingama/themes")
OUT = os.path.join(os.path.dirname(__file__), "..", "src", "themes.py")
PICK = [("linen-craft", "Linen Craft"), ("atelier-ivory", "Atelier Ivory"), ("boutique-rosewood", "Boutique Rosewood"),
        ("metropolitan-slate", "Metropolitan Slate"), ("nordic", "Nordic"), ("premium-light", "Premium Light"),
        ("premium-dark", "Premium Dark"), ("catppuccin-mocha", "Catppuccin Mocha"), ("pastel-night", "Pastel Night"),
        ("velvet", "Velvet"), ("gruvbox", "Gruvbox"), ("teal-orange-cyber", "Teal-Orange Cyber"),
        ("wallpaper-desert-calm", "Desert Calm"), ("wallpaper-desert-night", "Desert Night"),
        ("wallpaper-desert-cosmic-distortion", "Cosmic Dusk"), ("wallpaper-buildings", "City Dusk"),
        ("wallpaper-fantasy-japanese-street", "Neon Street")]
OWN = [
    dict(id="sunshine-dusk", label="Sunshine Dusk", bg="#101521", surface="#171d2b", surface_alt="#1d2433", panel="#141a27",
         primary="#e2b977", secondary="#e9e2d3", accent="#c18f55", edge="rgba(226,185,119,0.18)", source="Sunshine wallpaper"),
    dict(id="sunshine-dawn", label="Sunshine Dawn", bg="#f6efe3", surface="#fffaf1", surface_alt="#efe5d3", panel="#f1e8d8",
         primary="#8a5a2b", secondary="#2a2320", accent="#c18f55", edge="rgba(138,90,43,0.22)", source="Sunshine wallpaper"),
    dict(id="sunshine-lily", label="Sunshine Lily", bg="#15121c", surface="#1e1a27", surface_alt="#252033", panel="#1a1623",
         primary="#e59aa5", secondary="#efe4e1", accent="#d9a35f", edge="rgba(229,154,165,0.20)", source="Sunshine login image"),
]
def parse(path):
    css = open(path).read()
    v = dict(re.findall(r"--([a-z-]+)\s*:\s*([^;]+);", css))
    return {k: v[k].strip() for k in ("primary", "secondary", "accent", "bg", "surface") if k in v} | \
           {"surface_alt": v.get("surface-alt", v["surface"]).strip(), "panel": v.get("panel-bg", v["surface"]).strip(),
            "edge": v.get("edge", "").strip()}
themes = list(OWN)
for tid, label in PICK:
    t = parse(os.path.join(SRC, tid + ".css")); t.update(id=tid, label=label, source="Ingama Textil themes"); themes.append(t)
with open(OUT, "w") as f:
    f.write('"""Sunshine Store themes. Generated by tools/gen_themes.py.\n\nSunshine* themes come from the Sunshine OS wallpapers; the rest are palettes from the Ingama Textil theme set.\n'
            'Colour roles: bg = window, surface/surface_alt/panel = cards and panels, primary = brand/headings,\n'
            'secondary = text, accent = highlights and buttons, edge = lines.\n"""\n\nTHEMES = ')
    f.write(json.dumps(themes, indent=1))
    f.write('\n\nDEFAULT_THEME = "sunshine-dusk"\n')
print(len(themes), "themes written to", os.path.abspath(OUT))
